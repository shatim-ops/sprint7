def build_pattern(words):
    """Точное совпадение по слову, звёздочка в конце значит совпадение по основе.

    Регистр учитываем: имена собственные пишутся с заглавной,
    нарицательные вроде люка на корабле нас не интересуют.
    """
    parts = []
    for word in words:
        if word.endswith("*"):
            parts.append(re.escape(word[:-1]) + r"[а-яёА-ЯЁa-z0-9\-]*")
        else:
            parts.append(re.escape(word))
    body = "|".join(parts)
    return re.compile(r"(?<![а-яёА-ЯЁa-z0-9])(?:" + body + r")(?![а-яёА-ЯЁa-z0-9])")


def main() -> int:
    pattern = build_pattern(STOP_WORDS)
    problems = []
    for path in sorted(KB_DIR.glob("*.md")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for match in pattern.finditer(line):
                problems.append((path.name, number, match.group(0), line.strip()[:90]))

    if not problems:
        print(f"Стоп-слов не найдено, проверено файлов: {len(list(KB_DIR.glob('*.md')))}")
        return 0

    print(f"Найдено совпадений: {len(problems)}")
    for name, number, word, line in problems:
        print(f"  {name}:{number}  [{word}]  {line}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
